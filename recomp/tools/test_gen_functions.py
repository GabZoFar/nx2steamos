"""Differential test of whole generated functions: gen.py's C vs Unicorn.

Random guest programs of a few functions each, following the AArch64 calling convention: stack frames, the
registers a function preserves saved and restored, calls (BL) and indirect calls (BLR, through rt_dispatch) and tail calls
(B) down a chain of functions, system calls (SVC: the harness's rt_svc changes x0, as Unicorn's hook does), forward branches on
flags and on registers, counted loops, loads and stores in a buffer and in the frame. Each program is generated by
the real generator (discover, emit_function) into C, compiled with the host's C compiler and run from its first
function; every register, the flags, the buffer and the stack must come out as Unicorn's. test_lift.py and
test_simd.py check instructions one at a time; this checks what joins them: calls, returns, tail calls, branches.

usage: test_gen_functions.py [programs] [seed]   (default 300 programs; Unicorn and capstone, a C compiler as cc)
"""
import hashlib
import os
import random
import struct
import subprocess
import sys
import tempfile
from collections import Counter

import unicorn as uc
from unicorn import arm64_const as A

import gen
from lifter import Lifter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODE, CODE_SIZE = 0x7100000000, 0x10000   # each program's functions, one region per program
BUF, BUF_SIZE = 0x7200000000, 0x1000
STACK, STACK_SIZE = 0x7300000000, 0x10000
SENTINEL_OFF = 0xFFF0                       # (in a program's region: where its first function returns to)


# ---------------------------------------------------------------- AArch64 encodings used
def movz(d, imm, hw=0): return 0xD2800000 | hw << 21 | (imm & 0xFFFF) << 5 | d
def movk(d, imm, hw): return 0xF2800000 | hw << 21 | (imm & 0xFFFF) << 5 | d
def add_imm(d, n, imm): return 0x91000000 | (imm & 0xFFF) << 10 | n << 5 | d
def sub_imm(d, n, imm): return 0xD1000000 | (imm & 0xFFF) << 10 | n << 5 | d
def alu(op, d, n, m): return {'add': 0x8B000000, 'sub': 0xCB000000, 'eor': 0xCA000000, 'orr': 0xAA000000, 'and': 0x8A000000}[op] | m << 16 | n << 5 | d
def mul(d, n, m): return 0x9B007C00 | m << 16 | n << 5 | d
def cmp(n, m): return 0xEB00001F | m << 16 | n << 5
def csel(d, n, m, cond): return 0x9A800000 | m << 16 | cond << 12 | n << 5 | d
def ldr(t, n, off): return 0xF9400000 | (off // 8) << 10 | n << 5 | t
def str_(t, n, off): return 0xF9000000 | (off // 8) << 10 | n << 5 | t
def stp_pre(a, b, n, off): return 0xA9800000 | ((off // 8) & 0x7F) << 15 | b << 10 | n << 5 | a
def ldp_post(a, b, n, off): return 0xA8C00000 | ((off // 8) & 0x7F) << 15 | b << 10 | n << 5 | a
def blr(n): return 0xD63F0000 | n << 5
def svc(imm): return 0xD4000001 | imm << 5
RET = 0xD65F03C0
SP, BASE = 31, 27   # x27: the buffer, never written


# ---------------------------------------------------------------- random programs
def gen_function(r, i, nfun):
    """Items of function i: ('w', word), ('bl', j), ('addr', reg, j) (3 words: F_j's address), ('bcond', cond, rel),
    ('cbz', reg, nz, rel), ('b', rel); rel in words from the item itself."""
    saved = sorted(r.sample(range(19, 27), 2 * r.randint(0, 3)))          # callee-saved registers it uses
    temps = [x for x in range(16)]                                         # caller-saved it may write
    writable = temps + saved
    readable = writable + [BASE, 28] + [x for x in range(19, 27) if x not in saved]
    items = [('w', stp_pre(29, 30, SP, -16)), ('w', add_imm(29, SP, 0))]
    for a, b in zip(saved[0::2], saved[1::2]):
        items.append(('w', stp_pre(a, b, SP, -16)))
    items.append(('w', sub_imm(SP, SP, 32)))                               # 4 locals at [sp, #0..24]

    def simple(dst=None):
        d = dst if dst is not None else r.choice(writable)
        k = r.random()
        if k < 0.15: return ('w', movz(d, r.getrandbits(16), r.randint(0, 3)))
        if k < 0.45: return ('w', alu(r.choice(['add', 'sub', 'eor', 'orr', 'and']), d, r.choice(readable), r.choice(readable)))
        if k < 0.55: return ('w', add_imm(d, r.choice(readable), r.getrandbits(12)))
        if k < 0.62: return ('w', mul(d, r.choice(readable), r.choice(readable)))
        if k < 0.70: return ('w', csel(d, r.choice(readable), r.choice(readable), r.randint(0, 13)))
        if k < 0.80: return ('w', ldr(d, BASE, 8 * r.randint(0, 63)))
        if k < 0.88: return ('w', str_(r.choice(readable), BASE, 8 * r.randint(0, 63)))
        if k < 0.94: return ('w', str_(r.choice(readable), SP, 8 * r.randint(0, 3)))
        return ('w', ldr(d, SP, 8 * r.randint(0, 3)))

    for _ in range(r.randint(8, 40)):
        k = r.random()
        if k < 0.55:
            items.append(simple())
        elif k < 0.62:
            items.append(('w', cmp(r.choice(readable), r.choice(readable))))
        elif k < 0.70 and i + 1 < nfun:
            items.append(('bl', r.randint(i + 1, nfun - 1)))
        elif k < 0.76 and i + 1 < nfun:
            items += [('addr', 16, r.randint(i + 1, nfun - 1)), ('w', blr(16))]
        elif k < 0.80:
            items.append(('w', svc(r.randint(0, 3))))
        elif k < 0.88:  # a forward branch over a few simple instructions
            n = r.randint(1, 4)
            if r.random() < 0.5:
                items.append(('bcond', r.randint(0, 13), n + 1))
            else:
                items.append(('cbz', r.choice(readable), r.random() < 0.5, n + 1))
            items += [simple() for _ in range(n)]
        else:  # a counted loop, in a register its body leaves alone
            ctr = r.choice([x for x in temps if x != 16])
            body = [simple(r.choice([x for x in writable if x != ctr])) for _ in range(r.randint(1, 4))]
            items.append(('w', movz(ctr, r.randint(1, 4))))
            items += body
            items.append(('w', sub_imm(ctr, ctr, 1)))
            items.append(('cbz', ctr, True, -(len(body) + 1)))
    items.append(('w', add_imm(SP, SP, 32)))
    for a, b in reversed(list(zip(saved[0::2], saved[1::2]))):
        items.append(('w', ldp_post(a, b, SP, 16)))
    items.append(('w', ldp_post(29, 30, SP, 16)))
    # a tail call: the frame gone, the next function returns to this one's caller
    items.append(('bfn', r.randint(i + 1, nfun - 1)) if i + 1 < nfun and r.random() < 0.3 else ('w', RET))
    return items


def size(items):
    return sum(3 if it[0] == 'addr' else 1 for it in items)


def assemble(funcs, base):
    """Words of the program and its functions' addresses"""
    starts, a = [], base
    for f in funcs:
        starts.append(a)
        a += 4 * size(f)
    words = []
    for f, start in zip(funcs, starts):
        pos = [start]  # address of each item
        for it in f:
            pos.append(pos[-1] + (12 if it[0] == 'addr' else 4))
        for k, it in enumerate(f):
            pc = pos[k]
            if it[0] == 'w':
                words.append(it[1])
            elif it[0] in ('bl', 'bfn'):
                words.append((0x94000000 if it[0] == 'bl' else 0x14000000) | ((starts[it[1]] - pc) // 4) & 0x3FFFFFF)
            elif it[0] == 'addr':
                t = starts[it[2]]
                words += [movz(it[1], t), movk(it[1], t >> 16, 1), movk(it[1], t >> 32, 2)]
            elif it[0] == 'bcond':
                words.append(0x54000000 | (((pos[k + it[2]] - pc) // 4) & 0x7FFFF) << 5 | it[1])
            elif it[0] == 'cbz':
                words.append((0xB5000000 if it[2] else 0xB4000000) | (((pos[k + it[3]] - pc) // 4) & 0x7FFFF) << 5 | it[1])
    return words, starts


class Program(gen.Module):
    """A made-up module: the words of one program at base"""

    def __init__(self, words, base, starts):
        self.name, self.base = 'test', base
        self.lo, self.hi = base, base + 4 * len(words)
        self.words = words
        self.lifter = Lifter(base, 'c')
        self.cache, self.stats, self.mu, self.cs, self.jt_cache = {}, Counter(), None, None, {}
        ends = starts[1:] + [self.hi]
        self.fdes = list(zip(starts, ends))
        self.fde_starts = list(starts)
        self.setjmps, self.sites, self.patches = set(), {}, {}


# ---------------------------------------------------------------- the two runs
def run_unicorn(words, base, entry, state):
    mu = uc.Uc(uc.UC_ARCH_ARM64, uc.UC_MODE_ARM)
    mu.mem_map(base, CODE_SIZE)
    mu.mem_map(BUF, BUF_SIZE)
    mu.mem_map(STACK, STACK_SIZE)
    mu.mem_write(base, struct.pack(f'<{len(words)}I', *words))
    x, nzcv, buf = state
    mu.mem_write(BUF, buf)
    for i in range(29):
        mu.reg_write(A.UC_ARM64_REG_X0 + i, x[i])
    mu.reg_write(A.UC_ARM64_REG_X29, x[29])
    mu.reg_write(A.UC_ARM64_REG_X30, base + SENTINEL_OFF)
    mu.reg_write(A.UC_ARM64_REG_SP, STACK + STACK_SIZE)
    mu.reg_write(A.UC_ARM64_REG_NZCV, nzcv)

    def on_svc(mu, intno, _):
        pc = mu.reg_read(A.UC_ARM64_REG_PC)
        imm = (struct.unpack('<I', mu.mem_read(pc - 4, 4))[0] >> 5) & 0xFFFF
        mu.reg_write(A.UC_ARM64_REG_X0, (mu.reg_read(A.UC_ARM64_REG_X0) + 1 + imm) & (2**64 - 1))
    mu.hook_add(uc.UC_HOOK_INTR, on_svc)
    mu.emu_start(entry, base + SENTINEL_OFF, count=2000000)
    if mu.reg_read(A.UC_ARM64_REG_PC) != base + SENTINEL_OFF:
        raise RuntimeError('Unicorn did not come back')
    regs = [mu.reg_read(A.UC_ARM64_REG_X0 + i) for i in range(29)]
    regs += [mu.reg_read(A.UC_ARM64_REG_X29), mu.reg_read(A.UC_ARM64_REG_X30), mu.reg_read(A.UC_ARM64_REG_SP),
             mu.reg_read(A.UC_ARM64_REG_NZCV) & 0xF0000000]
    return regs, fnv(bytes(mu.mem_read(BUF, BUF_SIZE))), fnv(bytes(mu.mem_read(STACK, STACK_SIZE)))


def fnv(b):
    h = 0xcbf29ce484222325
    for v in struct.unpack(f'<{len(b) // 8}Q', b):
        h = ((h ^ v) * 0x100000001b3) & (2**64 - 1)
    return h


HARNESS = r'''
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
#include "cpu.h"
volatile int g_fnprof;
void fnprof_hit(uint64_t a, uint64_t lr, uint64_t x0) { (void)a; (void)lr; (void)x0; }
uint64_t rt_ticks(void) { return 0; }
void rt_udf(Cpu *c, uint64_t pc) { (void)c; fprintf(stderr, "udf %llx\n", (unsigned long long)pc); abort(); }
void rt_brk(Cpu *c, uint32_t imm, uint64_t pc) { (void)c; (void)imm; (void)pc; abort(); }
void rt_svc(Cpu *c, uint32_t imm, uint64_t pc) { (void)pc; c->x[0] += 1 + imm; }
void rt_dispatch(Cpu *c) {
    for (int i = 0; i < fn_count; i++)
        if (fn_addrs[i] == c->pc) { fn_ptrs[i](c); return; }
    fprintf(stderr, "dispatch to %llx\n", (unsigned long long)c->pc); abort();
}
static uint64_t fnv(const uint64_t *p, size_t n) {
    uint64_t h = 0xcbf29ce484222325ull;
    for (size_t i = 0; i < n / 8; i++) h = (h ^ p[i]) * 0x100000001b3ull;
    return h;
}
static void *map(uint64_t a, size_t n) {
    void *p = mmap((void *)(uintptr_t)a, n, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANON | MAP_FIXED, -1, 0);
    if (p != (void *)(uintptr_t)a) { perror("mmap"); exit(1); }
    return p;
}
int main(void) {
    uint64_t *buf = map(BUF_ADDR, BUF_SIZE), *stack = map(STACK_ADDR, STACK_SIZE);
    static Cpu c;
    for (int k = 0; k < ncases; k++) {
        memcpy(buf, cases[k].buf, BUF_SIZE);
        memset(stack, 0, STACK_SIZE);
        memset(&c, 0, sizeof c);
        memcpy(c.x, cases[k].x, 30 * 8);
        c.x[30] = cases[k].ret;
        c.sp = STACK_ADDR + STACK_SIZE;
        c.nzcv = cases[k].nzcv;
        c.excl_addr = ~0ull;
        c.pc = cases[k].entry;
        rt_dispatch(&c);
        for (int i = 0; i < 31; i++) printf("%llx ", (unsigned long long)c.x[i]);
        printf("%llx %llx %llx %llx\n", (unsigned long long)c.sp, (unsigned long long)(c.nzcv & 0xf0000000ull),
               (unsigned long long)fnv(buf, BUF_SIZE), (unsigned long long)fnv(stack, STACK_SIZE));
    }
    return 0;
}
'''


def main():
    nprog = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    seed = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    r = random.Random(seed)
    work = tempfile.mkdtemp(prefix='test_gen_functions_')
    c_fns, table, cases, expect = [], [], [], []
    for p in range(nprog):
        base = CODE + p * CODE_SIZE
        funcs = [gen_function(r, i, n) for n in (r.randint(1, 5),) for i in range(n)]
        words, starts = assemble(funcs, base)
        m = Program(words, base, starts)
        entries, _ = gen.discover(m, starts)
        for a in sorted(entries):
            end, labels, tables = entries[a]
            c_fns += m.emit_function(a, end, labels, tables, {})
            table.append(a)
        x = [r.getrandbits(64) if r.random() < 0.8 else r.choice([0, 1, 2**64 - 1]) for _ in range(30)]
        x[BASE] = BUF
        nzcv = r.getrandbits(4) << 28
        buf = bytes(r.getrandbits(8) for _ in range(BUF_SIZE))
        cases.append((starts[0], x, nzcv, buf, base + SENTINEL_OFF))
        expect.append(run_unicorn(words, base, starts[0], (x, nzcv, buf)))
    src = ['#include "cpu.h"\n', ''.join(f'void {gen.fname(a)}(Cpu *c);\n' for a in table)]
    src.append(f'#define BUF_ADDR {BUF:#x}ull\n#define BUF_SIZE {BUF_SIZE}\n#define STACK_ADDR {STACK:#x}ull\n#define STACK_SIZE {STACK_SIZE}\n')
    src.append(f'static const int fn_count = {len(table)};\n')
    src.append('static const uint64_t fn_addrs[] = {' + ','.join(f'{a:#x}ull' for a in table) + '};\n')
    src.append('static const GuestFn fn_ptrs[] = {' + ','.join(gen.fname(a) for a in table) + '};\n')
    src.append('static const struct { uint64_t entry, x[30], nzcv, ret; unsigned char buf[BUF_SIZE]; } cases[] = {\n')
    for entry, x, nzcv, buf, ret in cases:
        src.append(f'{{{entry:#x}ull, {{' + ','.join(f'{v:#x}ull' for v in x) + f'}}, {nzcv:#x}ull, {ret:#x}ull, {{'
                   + ','.join(str(b) for b in buf) + '}},\n')
    src.append('};\nstatic const int ncases = sizeof cases / sizeof *cases;\n')
    src += [HARNESS, '\n'.join(c_fns), '\n']
    path = os.path.join(work, 'functions.c')
    open(path, 'w').write(''.join(src))
    exe = os.path.join(work, 'functions')
    subprocess.check_call([os.environ.get('CC', 'cc'), '-O1', '-fno-strict-aliasing', '-w', '-I', os.path.join(ROOT, 'runtime'),
                           '-o', exe, path])
    out = subprocess.run([exe], capture_output=True, text=True)
    if out.returncode:
        sys.exit(f'the harness failed ({out.returncode}): {out.stderr.strip()[-500:]}')
    bad = 0
    for k, (line, (regs, hb, hs)) in enumerate(zip(out.stdout.splitlines(), expect)):
        got = [int(v, 16) for v in line.split()]
        want = regs + [hb, hs]
        if got != want:
            bad += 1
            if bad <= 5:
                names = [f'x{i}' for i in range(31)] + ['sp', 'nzcv', 'buffer', 'stack']
                diff = ', '.join(f'{n} {g:#x} (Unicorn {w:#x})' for n, g, w in zip(names, got, want) if g != w)
                print(f'program {k} (seed {seed}): {diff}')
    print(f'{len(cases)} programs, {len(table)} functions, {len(c_fns)} lines of C: {bad} differing from Unicorn')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
